/**
 * The three house feeds of launch A, taken from the launch project's own fixture files.
 *
 * `launches/a-payroll/test/fixtures/questions/feeds/<name>.json` is what launch A's tests, its
 * launch document and its manifest are all checked against: the parameters, the question prefix and
 * the body tail of each feed, byte for byte, and the feed id they hash to. The generator
 * (`gen-house-feeds.ts`) copies those fields into `src/generated/houseFeeds.ts`, and a test renders
 * the file again and fails when it differs, so the TypeScript side cannot drift from the bytes the
 * contracts were proven with.
 */
import { existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/** In Payroll's order: `FEED_A`, `FEED_B`, `FEED_C`. */
export const HOUSE_FEED_FILES = ["payrolls", "hires", "employers"] as const;

export const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
export const FEED_FIXTURES_REL = "launches/a-payroll/test/fixtures/questions/feeds";
export const HOUSE_FEEDS_FILE = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "src",
  "generated",
  "houseFeeds.ts",
);

interface FeedFixture {
  name: string;
  title: string;
  feedId: string;
  params: Record<string, string | number | boolean>;
  qPrefix: string;
  qPrefixHex: string;
  tail: string;
  tailHex: string;
}

/** The order `Questions.FeedParams` declares its fields in. */
const PARAM_KEYS = [
  "action",
  "chainId",
  "answerType",
  "panelSize",
  "quorum",
  "minAgreed",
  "validFor",
  "cadenceBlocks",
  "maxWindowBlocks",
  "lagBlocks",
  "contiguous",
  "pinHash",
  "maxPrice",
  "tip",
  "gateCmp",
  "gateTarget",
  "gateThreshold",
  "gateData",
] as const;

export function feedFixturePath(name: string, root: string = REPO_ROOT): string {
  return join(root, FEED_FIXTURES_REL, `${name}.json`);
}

/** True when all three fixture files are on disk. */
export function feedFixturesPresent(root: string = REPO_ROOT): boolean {
  return HOUSE_FEED_FILES.every((name) => existsSync(feedFixturePath(name, root)));
}

function pick(name: string, root: string): Record<string, unknown> {
  const fixture = JSON.parse(readFileSync(feedFixturePath(name, root), "utf8")) as FeedFixture;
  if (fixture.name !== name) throw new Error(`${name}.json names itself "${fixture.name}"`);
  const params: Record<string, unknown> = {};
  for (const key of PARAM_KEYS) {
    if (!(key in fixture.params)) throw new Error(`${name}.json has no params.${key}`);
    params[key] = fixture.params[key];
  }
  const extra = Object.keys(fixture.params).filter((k) => !(PARAM_KEYS as readonly string[]).includes(k));
  if (extra.length > 0) throw new Error(`${name}.json has parameters this generator does not know: ${extra}`);
  // The text and its bytes are both in the fixture; they must say the same thing.
  for (const [text, hex] of [
    [fixture.qPrefix, fixture.qPrefixHex],
    [fixture.tail, fixture.tailHex],
  ] as const) {
    if (`0x${Buffer.from(text, "utf8").toString("hex")}` !== hex) {
      throw new Error(`${name}.json: a text and its hex spelling differ`);
    }
  }
  return {
    name: fixture.name,
    title: fixture.title,
    feedId: fixture.feedId,
    params,
    qPrefix: fixture.qPrefix,
    qPrefixHex: fixture.qPrefixHex,
    tail: fixture.tail,
    tailHex: fixture.tailHex,
  };
}

/** The text of `src/generated/houseFeeds.ts`. */
export function renderHouseFeedsFile(root: string = REPO_ROOT): string {
  const data: Record<string, unknown> = {};
  for (const name of HOUSE_FEED_FILES) data[name] = pick(name, root);
  return (
    `// Generated by scripts/gen-house-feeds.ts from ${FEED_FIXTURES_REL}/*.json.\n` +
    "// Do not edit by hand. After a fixture changes, run `pnpm --filter @help-wanted/shared feeds:gen`.\n" +
    "// Amounts are decimal strings of IMD wei, as the fixtures write them.\n" +
    `\nexport const HOUSE_FEED_DATA = ${JSON.stringify(data, null, 2)} as const;\n`
  );
}
